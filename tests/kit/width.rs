/// 一个字符占几格：东亚宽字符两格，别的一格
pub fn of_char(c: char) -> usize {
    let cp = c as u32;
    let wide = WIDE
        .binary_search_by(|&(lo, hi)| {
            if cp < lo {
                std::cmp::Ordering::Greater
            } else if cp > hi {
                std::cmp::Ordering::Less
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok();
    if wide {
        2
    } else {
        1
    }
}

/// 一段文字占几格：各个字符加起来
pub fn of(text: &str) -> usize {
    text.chars().map(of_char).sum()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_is_sorted_and_complete() {
        let mut total = 0u32;
        let mut last: Option<u32> = None;
        for &(lo, hi) in WIDE {
            assert!(lo <= hi, "{lo:#X}..{hi:#X}");
            // 挨着的两段该合成一段：生成的时候就是这样的，手改漏了能看出来
            assert!(last.is_none_or(|end| lo > end + 1), "{lo:#X} 接在上一段后面");
            last = Some(hi);
            total += hi - lo + 1;
        }
        assert_eq!(WIDE.len(), 122);
        assert_eq!(total, 182719);
    }

    /// 对照数据是生成这张表时 Python 算的：(码位, 占几格)
    #[test]
    fn widths_like_python() {
        let cases: &[(&[u32], usize)] = &[
            (&[], 0),
            (&[0x61, 0x62, 0x63], 3),
            (&[0x8D26, 0x53F7], 4),
            (&[0x61, 0x8D26, 0x62, 0x53F7], 6),
            (&[0xFF21, 0xFF22], 4),
            (&[0x3000], 2),
            (&[0x65, 0x301], 2),
            (&[0x1F600], 2),
            (&[0xE9], 1),
            (&[0x55, 0x53, 0x2D, 0x41, 0xFF08, 0x5B98, 0x65B9, 0xFF09], 12),
            (&[0x2026], 1),
            (&[0x1100, 0x1160], 3),
            (&[0x20000], 2),
            (&[0xD7A3], 2),
            (&[0x303F], 1),
            (&[0x2E80], 2),
            (&[0xA4C6], 2),
            (&[0xFFE6, 0xFFE8], 3),
            (&[0x9, 0x1B], 2),
            (&[0x2500, 0x2502], 2),
            (&[0x25CF], 1),
            (&[0x2713, 0x2717], 2),
            (&[0x3FFFD], 2),
            (&[0x1F1E6], 1),
        ];
        for (cps, want) in cases {
            let text: String = cps.iter().map(|&cp| char::from_u32(cp).expect("码位")).collect();
            assert_eq!(of(&text), *want, "{cps:X?}");
        }
    }
}
